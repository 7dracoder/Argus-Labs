// Run against a local preview. Uses the configured AI for one research note.
// Install Playwright + Chrome, or supply NODE_PATH to the bundled runtime.
import {createRequire} from 'node:module';
import {mkdir, writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const {chromium} = createRequire(import.meta.url)('playwright');
const base = process.env.ARGUS_TEST_URL || 'http://127.0.0.1:8766';
assert.match(base, /^http:\/\/127\.0\.0\.1:\d+$/);
const output = 'artifacts/dev/studio-e2e';
await mkdir(output, {recursive:true});
const browser = await chromium.launch({channel:'chrome',headless:true});
const context = await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
const page = await context.newPage();
const errors = [], results = {};
page.on('pageerror', e=>errors.push(e.message));
page.setDefaultTimeout(180000);
const record = (key, value=true)=>{results[key]=value; console.log(JSON.stringify({[key]:value}));};
try {
  await page.goto(base);
  await page.waitForFunction(()=>document.querySelector('#sample')?.disabled===false);
  assert.equal(await page.evaluate(()=>getComputedStyle(document.body).backgroundColor),'rgb(255, 255, 255)');
  await page.locator('#showcase-stage canvas').waitFor();
  await page.waitForFunction(()=>!document.querySelector('#showcase-stage').classList.contains('loading'));
  await page.waitForFunction(()=>getComputedStyle(document.querySelector('.sc-caption h2')).opacity==='1');
  await page.screenshot({path:`${output}/white-home.png`,fullPage:true});
  record('white_theme');
  await page.locator('#sample').click();
  await page.locator('#workspace').waitFor({state:'visible'});
  await page.waitForFunction(()=>document.querySelector('#cad-form button[type=submit]')?.disabled===false);
  assert.ok(await page.locator('#bom-lines li').count());
  record('design_bom');
  await page.locator('#cad-form button[type=submit]').click();
  await page.waitForFunction(()=>document.querySelector('#part-details')?.textContent.includes('built:'));
  const link = page.locator('#downloads a').filter({hasText:'STEP'}).first();
  const href = await link.getAttribute('href');
  const artifact = await context.request.get(new URL(href,base).href);
  assert.equal(artifact.status(),200); assert.ok((await artifact.body()).includes(Buffer.from('ISO-10303-21')));
  record('real_cad_download');
  await page.locator('#cheaper').click();
  await page.waitForFunction(()=>document.querySelector('#research-form button[type=submit]')?.disabled===false);
  record('cost_optimization');
  await page.locator('#research-form button[type=submit]').click();
  await page.locator('#research-results').waitFor({state:'visible'});
  assert.equal(await page.locator('#research-companies tr').count(),2);
  assert.equal(await page.locator('#research-economics tr').count(),3);
  assert.equal(await page.locator('#research-sources li').count(),10);
  assert.ok((await page.locator('#research-evaluation').innerText()).includes('3 held-out annual periods'));
  record('financial_research',await page.locator('#research-status').innerText());
  if (process.env.ARGUS_EXPECT_AI === '1') assert.match(await page.locator('#research-status').innerText(),/AI note generated/);
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#research-export').click();
  const download=await downloadPromise; await download.saveAs(`${output}/research.json`);
  record('research_export');
  await page.locator('.finance-research').screenshot({path:`${output}/financial-research.png`});
  await page.locator('#to-assemble').click();
  await page.locator('#assemble').waitFor({state:'visible'});
  assert.ok(await page.locator('#asm-prints li').count());
  record('assembly_guide');
  await page.locator('#back-to-design').click();
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
  await page.screenshot({path:`${output}/white-mobile.png`,fullPage:true});
  record('mobile_no_page_overflow');
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#new-robot').click();
  await page.locator('#brief').fill('A delivery rover that carries 5 kg packages between rooms in our office for three hours a day.');
  await page.locator('#budget').fill('1800');
  await page.locator('#start-form button[type=submit]').click();
  await page.locator('#workspace').waitFor({state:'visible'});
  assert.ok((await page.locator('#project-title').innerText()).length>0);
  assert.ok(await page.locator('#bom-lines li').count());
  record('natural_language_design');
  record('javascript_errors',errors); assert.equal(errors.length,0);
} finally {
  await writeFile(`${output}/result.json`,JSON.stringify(results,null,2));
  await browser.close();
}
